const DICTS: Record<Lang, Dict> = { en, te, hi };

type TFn = (key: TKey, params?: Record<string, string | number>) => string;
const I18nContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: TFn }>({
  lang: 'en',
  setLang: () => {},
  t: (k) => en[k],
});

const STORAGE_KEY = 'nagrik.lang';

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const device = getLocales()[0]?.languageCode;
    return device === 'te' || device === 'hi' ? device : 'en';
  });

  useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY)
      .then((v) => {
        if (v === 'en' || v === 'te' || v === 'hi') setLangState(v);
      })
      .catch(() => {});
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    AsyncStorage.setItem(STORAGE_KEY, l).catch(() => {});
  }, []);

  const t = useCallback<TFn>(
    (key, params) => {
      let s = DICTS[lang][key] ?? en[key] ?? key;
      if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
      return s;
    },
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
